using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;

/// <summary>
/// Assets/**/Resources 폴더를 훑어서 AssetPaths.g.cs 를 생성한다.
/// Resources 안의 파일이 추가/삭제/이동되면 자동으로 다시 생성된다.
/// </summary>
internal sealed class AssetPathsGenerator : AssetPostprocessor
{
    private const string OutputPath = "Assets/Scripts/AssetLoading/AssetPaths.g.cs";
    private const string ResourcesSegment = "/Resources/";

    private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
        "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern",
        "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface",
        "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override",
        "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
        "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
        "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
    };

    private static bool scheduled;

    private sealed class Folder
    {
        public Folder(string path) => Path = path;

        public readonly string Path;
        public readonly SortedDictionary<string, Folder> Children = new(StringComparer.Ordinal);
        public readonly SortedDictionary<string, string> Files = new(StringComparer.Ordinal);
    }

    [MenuItem("Tools/Asset Loader/Regenerate Asset Paths")]
    private static void RegenerateFromMenu() => Generate(logResult: true);

    private static void OnPostprocessAllAssets(string[] importedAssets, string[] deletedAssets, string[] movedAssets, string[] movedFromAssetPaths)
    {
        if (scheduled)
            return;
        if (!importedAssets.Concat(deletedAssets).Concat(movedAssets).Concat(movedFromAssetPaths).Any(IsResourcesAsset))
            return;

        // 한 번에 여러 파일이 바뀌어도 한 번만 생성한다.
        scheduled = true;
        EditorApplication.delayCall += () =>
        {
            scheduled = false;
            Generate(logResult: false);
        };
    }

    private static void Generate(bool logResult)
    {
        var paths = CollectPaths();
        var code = BuildCode(paths);

        if (File.Exists(OutputPath) && File.ReadAllText(OutputPath) == code)
        {
            if (logResult)
                Debug.Log($"[AssetLoader] AssetPaths 가 이미 최신입니다. ({paths.Count}개)");
            return;
        }

        Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));
        File.WriteAllText(OutputPath, code, new UTF8Encoding(false));
        AssetDatabase.ImportAsset(OutputPath);
        Debug.Log($"[AssetLoader] AssetPaths 를 갱신했습니다. ({paths.Count}개)");
    }

    private static bool IsResourcesAsset(string assetPath)
        => assetPath.StartsWith("Assets/", StringComparison.Ordinal)
           && assetPath.Contains(ResourcesSegment)
           && !assetPath.Contains("/Editor/");

    private static List<string> CollectPaths()
    {
        var set = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var assetPath in AssetDatabase.GetAllAssetPaths())
        {
            if (!IsResourcesAsset(assetPath) || AssetDatabase.IsValidFolder(assetPath))
                continue;
            if (assetPath.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
                continue;

            var path = assetPath.Substring(assetPath.LastIndexOf(ResourcesSegment, StringComparison.Ordinal) + ResourcesSegment.Length);
            var extension = Path.GetExtension(path);
            if (extension.Length > 0)
                path = path.Substring(0, path.Length - extension.Length);
            if (path.Length > 0)
                set.Add(path);
        }
        return set.ToList();
    }

    private static string BuildCode(IReadOnlyList<string> paths)
    {
        var root = new Folder(string.Empty);
        foreach (var path in paths)
        {
            var parts = path.Split('/');
            var folder = root;
            for (var i = 0; i < parts.Length - 1; i++)
            {
                if (!folder.Children.TryGetValue(parts[i], out var child))
                {
                    child = new Folder(folder.Path.Length == 0 ? parts[i] : folder.Path + "/" + parts[i]);
                    folder.Children.Add(parts[i], child);
                }
                folder = child;
            }
            folder.Files[parts[^1]] = path;
        }

        var sb = new StringBuilder();
        sb.Append("// <auto-generated>\n");
        sb.Append("// Resources 폴더를 기준으로 자동 생성되는 파일입니다. 직접 수정하지 마세요.\n");
        sb.Append("// Resources 내용이 바뀌면 자동 갱신되며, 수동 갱신은 Tools > Asset Loader > Regenerate Asset Paths.\n");
        sb.Append("// </auto-generated>\n");
        sb.Append("using System.Collections.Generic;\n\n");
        sb.Append("public static class AssetPaths\n{\n");
        sb.Append("    public static readonly IReadOnlyList<string> All = new string[]\n    {\n");
        foreach (var path in paths)
            sb.Append("        ").Append(Literal(path)).Append(",\n");
        sb.Append("    };\n");
        if (root.Files.Count > 0)
            sb.Append('\n');
        WriteMembers(sb, root, 1, new HashSet<string>(StringComparer.Ordinal) { "AssetPaths", "All" });
        sb.Append("}\n");
        return sb.ToString();
    }

    private static void WriteMembers(StringBuilder sb, Folder folder, int depth, HashSet<string> used)
    {
        var indent = new string(' ', depth * 4);

        // 폴더(클래스) 이름을 먼저 정해서, 파일 이름과 겹치면 파일 쪽에 접미사를 붙인다.
        var folderNames = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var child in folder.Children)
            folderNames[child.Key] = Unique(Identifier(child.Key), used);

        foreach (var file in folder.Files)
            sb.Append(indent).Append("public const string ").Append(Unique(Identifier(file.Key), used))
              .Append(" = ").Append(Literal(file.Value)).Append(";\n");

        foreach (var child in folder.Children)
        {
            var name = folderNames[child.Key];
            var inner = indent + "    ";
            sb.Append('\n');
            sb.Append(indent).Append("public static class ").Append(name).Append('\n');
            sb.Append(indent).Append("{\n");
            sb.Append(inner).Append("public const string Folder = ").Append(Literal(child.Value.Path)).Append(";\n");
            WriteMembers(sb, child.Value, depth + 1, new HashSet<string>(StringComparer.Ordinal) { name, "Folder" });
            sb.Append(indent).Append("}\n");
        }
    }

    private static string Identifier(string name)
    {
        var sb = new StringBuilder(name.Length + 1);
        foreach (var c in name)
            sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
        if (sb.Length == 0 || char.IsDigit(sb[0]))
            sb.Insert(0, '_');

        var id = sb.ToString();
        return Keywords.Contains(id) ? "@" + id : id;
    }

    private static string Unique(string id, HashSet<string> used)
    {
        var candidate = id;
        for (var n = 2; !used.Add(candidate); n++)
            candidate = id + "_" + n;
        return candidate;
    }

    private static string Literal(string value)
        => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
